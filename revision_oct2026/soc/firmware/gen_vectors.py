#!/usr/bin/env python3
# Emits vectors.h from the ascon-c LWC KAT file (sim/kat) + the ref_gen 1 KiB vector (sim2/vec_a32_p1024_*).
# Count = 33*ptlen + adlen + 1 in LWC_AEAD_KAT_128_128.txt (pt/ad lengths 0..32).
import sys
root = sys.argv[1]   # ascon_claude dir
kat = {}
for blk in open(f"{root}/sim/kat/LWC_AEAD_KAT_128_128.txt").read().split("\n\n"):
    f = dict(l.split(" = ", 1) for l in blk.strip().splitlines() if " = " in l)
    if "Count" in f: kat[int(f["Count"])] = f
def hx(s): return bytes.fromhex(s.strip())
def lines(p): return bytes(int(x, 16) for x in open(p).read().split())
CASES = [(0, 0), (5, 0), (0, 7), (16, 16), (13, 19), (32, 32)]   # (adlen, ptlen)
out = ["// generated by gen_vectors.py -- do not edit", "#include <stdint.h>",
       "typedef struct { const char *name; uint32_t adlen, ptlen; const uint8_t *ad, *pt, *ct; } vec_t;"]
vecs = []
def arr(n, b): return f"static const uint8_t {n}[{max(len(b),1)}] = {{" + ",".join(f"0x{x:02x}" for x in b or b"\0") + "};"
for i, (a, p) in enumerate(CASES):
    f = kat[33 * p + a + 1]
    assert hx(f["Key"]) == bytes(range(16)) and hx(f["Nonce"]) == bytes(range(16, 32))
    ad, pt, ct = hx(f["AD"]), hx(f["PT"]), hx(f["CT"])
    assert len(ad) == a and len(pt) == p and len(ct) == p + 16
    out += [arr(f"ad{i}", ad), arr(f"pt{i}", pt), arr(f"ct{i}", ct)]
    vecs.append((f"KAT#{33*p+a+1} ad={a} pt={p}", a, p, i))
d = f"{root}/sim2/vec_a32_p1024"
ad, pt, ct = lines(d + "_ad.hex"), lines(d + "_pt.hex"), lines(d + "_exp.hex")
assert len(ad) == 32 and len(pt) == 1024 and len(ct) == 1040
n = len(CASES)
out += [arr(f"ad{n}", ad), arr(f"pt{n}", pt), arr(f"ct{n}", ct)]
vecs.append(("ref_gen ad=32 pt=1024", 32, 1024, n))
out.append("static const vec_t VECS[] = {")
out += [f'  {{"{nm}", {a}, {p}, ad{i}, pt{i}, ct{i}}},' for nm, a, p, i in vecs]
out.append("};")
out.append(f"#define NVEC {len(vecs)}")
out.append(f"#define IDX_1KB {n}")
print("\n".join(out))
